import {CalculationRangeError,Decimal,settleCents} from '../money';
import type {AduBookTreatments,AduFinancing,AduProject,AduTaxPayment,AduTaxSplit,Cents,History,PlanDocument,Property,RentalUnit,TaxBook,ValidatedPlan} from '../model/plan';
import type {RuleProvenance} from '../model/results';
import {validatePlan} from '../validation';
import {calculateAduLoanSchedule} from './adu-loans';

const books:readonly TaxBook[]=['federal','california','federal-amt','california-amt'];
const ordinaryKeys=['ordinaryResidential','longTermFairMarketLease','noPersonalUse','noSubstantialTenantServices','advancedBasisAdjustments'] as const;
const known=<T>(answer:History<T>,value:T):History<T>=>answer.known?answer:{known:true,value};
const emptySplit=():AduTaxSplit=>({buildingBasisCents:0,currentDeductionCents:0,nondepreciableBasisCents:0,nondeductibleExpenseCents:0});

/** Recognize only the unanswered shape generated by the former basic project setup. */
function untouchedLegacyProject(project:AduProject,unit:RentalUnit):boolean {
  const tax=project.propertyTax,loan=project.financing;
  if(project.costs.length!==1||project.costs.some(cost=>cost.category!=='building'||cost.paymentDate!==project.completionDate||books.some(book=>cost.treatments[book].known)))return false;
  if(books.some(book=>project.taxQualifications[book].known)||ordinaryKeys.some(key=>unit.qualifications[key].known)||unit.qualifications.californiaSmallBusinessQualification?.known)return false;
  if(unit.activeParticipation.known||unit.qbi.qualification.known||unit.qbi.wagesCents.known||unit.qbi.ubiaCents.known||unit.convertedFromPersonalUse||unit.loanAllocations.length||unit.sharedAllocation||project.sharedExpenseOverrides.length)return false;
  if(project.productionPeriod.known||project.supportOperatingDeficits.known||tax.addedAssessedValueCents.known||tax.marginalRateBps.known||tax.originalExpenseExcludesAdu.known||tax.additionalAnnualChargesCents!==0||tax.annualAssessmentGrowthBps!==200||tax.constructionAssessments.length)return false;
  if(tax.paymentYears.some(row=>row.complete.known||row.payments.length))return false;
  if(books.some(book=>{const history=unit.taxHistory[book];return !history.known||Object.entries(history.value).some(([field,value])=>field==='lossVintages'?!(Array.isArray(value)&&value.length===0):value!==0);}))return false;
  if(!unit.qbi.openingLossVintages.known||unit.qbi.openingLossVintages.value.length)return false;
  if(loan&&(loan.interestTaxRows.length||loan.draws.length!==1||loan.draws[0]!.costAllocations.length!==1||loan.draws[0]!.costAllocations[0]!.costId!==project.costs[0]!.id||loan.proceedsHistoryComplete.known||loan.rentalInterestQualified.known||loan.financingAtRiskQualification.known))return false;
  return true;
}

export function usesAduPlanningEstimates(property:Property,unit:RentalUnit):boolean {
  const project=property.aduProject;
  if(!project||project.rentalId!==unit.id||unit.propertyId!==property.id)return false;
  return project.taxEstimation?.mode==='simple'||project.taxEstimation===undefined&&untouchedLegacyProject(project,unit);
}

function deriveTreatments(treatments:AduBookTreatments,amount:Cents,category:keyof AduTaxSplit):AduBookTreatments {
  return Object.fromEntries(books.map(book=>[book,known(treatments[book],{...emptySplit(),[category]:amount})])) as AduBookTreatments;
}

function independentAssessment(project:AduProject):History<Cents> {
  if(project.propertyTax.addedAssessedValueCents.known)return project.propertyTax.addedAssessedValueCents;
  if(project.costs.some(cost=>cost.category!=='building'&&cost.amountCents>0))return {known:false};
  try{return {known:true,value:settleCents(project.costs.filter(cost=>cost.category==='building').reduce((total,cost)=>total.plus(cost.amountCents),new Decimal(0))) };}
  catch(error){if(!(error instanceof CalculationRangeError))throw error;return {known:false};}
}

/** This is an explicit cash-planning schedule, independently of actual assessment or bill timing. */
function estimatedAnnualPayment(project:AduProject,year:number):Cents|undefined {
  const completionYear=Number(project.completionDate.slice(0,4)),completionMonth=Number(project.completionDate.slice(5,7));
  const months=year<completionYear?0:year===completionYear?12-completionMonth:12;
  if(months===0)return 0;
  const tax=project.propertyTax;
  if(!tax.addedAssessedValueCents.known||!tax.marginalRateBps.known)return undefined;
  try{
    const growth=new Decimal(1).plus(new Decimal(tax.annualAssessmentGrowthBps).div(10000)).pow(Math.max(0,year-tax.completedValueEnrollmentYear));
    return settleCents(new Decimal(tax.addedAssessedValueCents.value).times(growth).times(tax.marginalRateBps.value).div(10000).plus(tax.additionalAnnualChargesCents).times(months).div(12));
  }catch(error){if(!(error instanceof CalculationRangeError))throw error;return undefined;}
}

function existingPayment(payment:AduTaxPayment,unit:RentalUnit):AduTaxPayment {
  if(payment.kind!=='regular')return payment;
  const paymentDate=calendarDate(Number(payment.month.slice(0,4)),Number(payment.month.slice(5,7)),31);
  return {...payment,treatments:deriveTreatments(payment.treatments,payment.amountCents,paymentDate<unit.availableDate?'buildingBasisCents':'currentDeductionCents')};
}

function identifiers(document:PlanDocument):Set<string> {
  const result=new Set<string>();
  const visit=(value:unknown):void=>{
    if(!value||typeof value!=='object')return;
    if(Array.isArray(value)){value.forEach(visit);return;}
    const record=value as Record<string,unknown>;
    if(typeof record.id==='string')result.add(record.id);
    Object.values(record).forEach(visit);
  };
  visit(document);return result;
}

function nextId(ids:Set<string>,base:string):string {
  let result=base,index=1;
  while(ids.has(result))result=`${base}:${index++}`;
  ids.add(result);return result;
}

function estimatedTaxSchedule(project:AduProject,unit:RentalUnit,plan:ValidatedPlan,ids:Set<string>):AduProject['propertyTax']['paymentYears'] {
  const existing=project.propertyTax.paymentYears.map(row=>({...row,payments:row.payments.map(payment=>existingPayment(payment,unit))}));
  const rows=new Map(existing.map(row=>[row.year,row]));
  for(let year=plan.startYear;year<plan.startYear+plan.horizonYears;year++){
    const row=rows.get(year);
    // A confirmed zero, explicit incomplete schedule, or entered bill is independent evidence.
    if(row&&(row.complete.known||row.payments.length))continue;
    const amount=estimatedAnnualPayment(project,year);
    if(amount===undefined){if(!row)rows.set(year,{year,complete:{known:false},payments:[]});continue;}
    const treatments=Object.fromEntries(books.map(book=>[book,{known:false}])) as AduBookTreatments;
    const payments:AduTaxPayment[]=amount===0?[]:[existingPayment({id:nextId(ids,`${project.id}:estimated-property-tax:${year}`),kind:'regular',month:`${year}-12`,amountCents:amount,treatments},unit)];
    rows.set(year,{year,complete:{known:true,value:true},payments});
  }
  return [...rows.values()].sort((a,b)=>a.year-b.year);
}

function estimatedFinancing(property:Property,unit:RentalUnit,plan:ValidatedPlan,ids:Set<string>):AduProject {
  const project=property.aduProject!,original=project.financing;
  if(!original)return project;
  let financing:AduFinancing={...original,proceedsHistoryComplete:known(original.proceedsHistoryComplete,true),rentalInterestQualified:known(original.rentalInterestQualified,true),financingAtRiskQualification:known(original.financingAtRiskQualification,true)};
  const resolved={...project,financing};
  if(project.costs.some(cost=>cost.category!=='building')||!financing.proceedsHistoryComplete.known||!financing.proceedsHistoryComplete.value||!financing.rentalInterestQualified.known||!financing.rentalInterestQualified.value)return resolved;
  const horizon=Math.min(plan.horizonYears,Math.max(1,Number(unit.availableDate.slice(0,4))-plan.startYear+1));
  const schedule=calculateAduLoanSchedule({...property,aduProject:resolved},plan.startYear,horizon);
  if(schedule.status!=='available')return resolved;
  let period=project.productionPeriod;
  const candidatePeriod=period.known?period.value:{startDate:project.constructionStartDate,endDate:project.completionDate,uninterrupted:true};
  const rows=new Map(financing.interestTaxRows.map(row=>[row.month,row]));
  for(const month of schedule.value.months){
    if(month.interestCents===0||`${month.date.slice(0,7)}-01`>=unit.availableDate)continue;
    const key=month.date.slice(0,7);
    if(!candidatePeriod.uninterrupted||candidatePeriod.startDate>month.date||candidatePeriod.endDate<`${key}-01`)continue;
    period=known(period,candidatePeriod);
    const row=rows.get(key),treatments=row?.treatments??Object.fromEntries(books.map(book=>[book,{known:false}])) as AduBookTreatments;
    rows.set(key,{id:row?.id??nextId(ids,`${project.id}:estimated-interest:${key}`),month:key,treatments:deriveTreatments(treatments,month.interestCents,'buildingBasisCents')});
  }
  financing={...financing,interestTaxRows:[...rows.values()].sort((a,b)=>a.month.localeCompare(b.month))};
  return {...project,productionPeriod:period,financing};
}

/** Derive disposable calculation inputs; saved facts and unrelated unknown history are never changed. */
export function resolveAduPlanningEstimates(plan:ValidatedPlan):ValidatedPlan {
  const ids=identifiers(plan),units=new Map(plan.rentals.map(unit=>[unit.id,unit]));
  let changed=false;
  const properties=plan.properties.map(property=>{
    const project=property.aduProject,original=project&&units.get(project.rentalId);
    if(!project||!original||!usesAduPlanningEstimates(property,original))return property;
    changed=true;
    const unit:RentalUnit={...original,activeParticipation:known(original.activeParticipation,false),qualifications:{...original.qualifications,
      ordinaryResidential:known(original.qualifications.ordinaryResidential,true),longTermFairMarketLease:known(original.qualifications.longTermFairMarketLease,true),noPersonalUse:known(original.qualifications.noPersonalUse,true),noSubstantialTenantServices:known(original.qualifications.noSubstantialTenantServices,true),advancedBasisAdjustments:known(original.qualifications.advancedBasisAdjustments,false),californiaSmallBusinessQualification:known(original.qualifications.californiaSmallBusinessQualification??{known:false},false)},
      qbi:{...original.qbi,qualification:known(original.qbi.qualification,false)},
    };
    units.set(unit.id,unit);
    const estimation=project.taxEstimation?.mode==='simple'?project.taxEstimation:{mode:'simple' as const,propertyTaxRateBps:120};
    let derived:AduProject={...project,taxEstimation:estimation,costs:project.costs.map(cost=>cost.category==='building'?{...cost,treatments:deriveTreatments(cost.treatments,cost.amountCents,'buildingBasisCents')}:cost),
      taxQualifications:Object.fromEntries(books.map(book=>[book,known(project.taxQualifications[book],true)])) as AduProject['taxQualifications'],supportOperatingDeficits:known(project.supportOperatingDeficits,true),
      propertyTax:{...project.propertyTax,addedAssessedValueCents:independentAssessment(project),completedValueEnrollmentYear:project.propertyTax.addedAssessedValueCents.known?project.propertyTax.completedValueEnrollmentYear:Math.min(9999,Number(project.completionDate.slice(0,4))+1),marginalRateBps:known(project.propertyTax.marginalRateBps,estimation.propertyTaxRateBps),originalExpenseExcludesAdu:known(project.propertyTax.originalExpenseExcludesAdu,true)},
    };
    derived={...derived,propertyTax:{...derived.propertyTax,paymentYears:estimatedTaxSchedule(derived,unit,plan,ids)}};
    derived=estimatedFinancing({...property,aduProject:derived},unit,plan,ids);
    return {...property,aduProject:derived};
  });
  if(!changed)return plan;
  const resolved=validatePlan({...plan,properties,rentals:plan.rentals.map(unit=>units.get(unit.id)!)});
  // Unsupported arithmetic is left unanswered for the normal availability gates.
  return resolved.ok?resolved.plan:plan;
}

export function aduEstimateProvenance(year:number):RuleProvenance {
  return {status:'provisional',ruleVersion:'adu-simple-estimate.1',baselineYear:2026,applicableYear:year,
    sources:['https://www.irs.gov/publications/p527','https://www.irs.gov/publications/p551','https://www.boe.ca.gov/proptaxes/newconstructionproperty.htm','https://www.boe.ca.gov/proptaxes/supplemental-assessment/'],
    assumptions:[
      'Simple ADU results are provisional planning estimates; they do not establish complete household tax liability or confirm unanswered tax qualifications.',
      'Unanswered rental qualifications assume an ordinary residential long-term fair-market rental with no personal use, substantial tenant services or advanced basis adjustments.',
      'Eligible building costs are assumed fully capitalized in all four tax books and use the existing ordinary residential recovery method; land, borrowing fees and other components receive no inferred recovery treatment.',
      'No unestablished active-participation special allowance, QBI deduction or California AMT small-business exclusion is claimed.',
      'An unknown added assessment uses eligible building cost as an explicit proxy; actual assessed added market value can differ from both cost and completion market value.',
      'Incremental property-tax cash uses the configurable planning rate (initially 1.2%, not a verified local rate), entered assessment growth and charges. Payments start the month following completion, are prorated in that year and are assumed paid in December. Entered assessments retain their enrollment year; a cost proxy starts full-year assessment growth after the following year.',
      'No incremental property-tax payments are assumed before completion in the simple schedule; construction-in-progress assessments and actual supplemental bill timing require detailed inputs. Existing original-property expenses are assumed to exclude incremental ADU bills.',
      'Unknown financing tracing and at-risk qualifications assume ordinary dedicated rental borrowing. Supported pre-readiness construction interest is capitalized during an assumed uninterrupted project production period; unqualified periods remain unresolved.',
      'The owner is assumed to support project operating deficits. Household funding gaps remain conditional and are not treated as available cash.',
      'Explicitly entered qualifications, tax-book splits, assessment inputs, payment schedules and financing decisions override these assumptions; unrelated missing household history remains unresolved.',
    ]};
}
